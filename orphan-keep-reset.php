<?php

require_once 'wp-load.php';


/**
 * =========================================================
 * SECURITY
 * =========================================================
 */

if (!is_user_logged_in()) {
	wp_die('Требуется авторизация.');
}

if (!current_user_can('manage_options')) {
	wp_die('Недостаточно прав.');
}


/**
 * =========================================================
 * KEEP STORAGE
 * =========================================================
 */

$keep_dir = WP_CONTENT_DIR . '/uploads/wp-cleanup';

$keep_file = $keep_dir . '/keep-ids.json';


/**
 * =========================================================
 * DELETE KEEP FILE
 * =========================================================
 */

if (file_exists($keep_file)) {

	unlink($keep_file);
}


/**
 * =========================================================
 * DELETE DIRECTORY
 * =========================================================
 *
 * Если папка пустая:
 * удаляем тоже
 */

if (
	file_exists($keep_dir)
	&&
	count(scandir($keep_dir)) <= 2
) {

	rmdir($keep_dir);
}


/**
 * =========================================================
 * OUTPUT
 * =========================================================
 */

echo '<h1>Keep list очищен.</h1>';

echo '<p>';

echo '<a href="orphan-unattached-images.php">';

echo 'Вернуться к cleaner';

echo '</a>';

echo '</p>';
